"""
PowerContext Client - learning memory and context for StudyMind.

PowerContext provides:
- Memory: store / recall learning progress, weak points, search behaviour
- Scope:  isolate memory per learner (a Scope is created on first run)
- Context: prepare a citation-bearing context block for the answer flow

Verified against PowerContext Server 1.4.1:
- GET  /health/ready
- POST /v1/scopes                       create a learning Scope
- POST /v1/memory/remember              write a memory entry
- POST /v1/memory/search                recall memories by relevance
- POST /v1/context/prepare              prepared context with citations

Notes
-----
The Scope id is generated by the server, so the first successful creation is
cached in `qoder/.powercontext-scope.json` and reused on later runs.
`trust_env = False` keeps local proxy settings from intercepting localhost.
"""

import os
import json
import logging
import requests
from datetime import datetime

from config import Config

logger = logging.getLogger(__name__)

_SCOPE_CACHE = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', '.powercontext-scope.json'
)


class PowerContextClient:
    """Client for the PowerContext Server HTTP API."""

    def __init__(self, base_url=None, scope_id=None):
        self.base_url = (base_url or Config.POWERCONTEXT_API_URL).rstrip('/')
        self.scope_id = scope_id or Config.POWERCONTEXT_SCOPE_ID
        self.session = requests.Session()
        self.session.headers.update({'Content-Type': 'application/json'})
        self.session.trust_env = False
        self.scope_ready = False

    # ---------- transport ----------

    def _url(self, path):
        return f'{self.base_url}{path}'

    def _post(self, path, payload, timeout=15):
        try:
            resp = self.session.post(self._url(path), json=payload, timeout=timeout)
            if resp.status_code >= 400:
                logger.warning('PowerContext %s -> %s %s', path, resp.status_code,
                               resp.text[:200])
                return None
            return resp.json()
        except Exception as exc:
            logger.warning('PowerContext %s failed: %s', path, exc)
            return None

    # ---------- scope ----------

    @staticmethod
    def _read_cached_scope():
        try:
            with open(_SCOPE_CACHE, 'r', encoding='utf-8') as fh:
                return json.load(fh).get('scope_id')
        except Exception:
            return None

    @staticmethod
    def _write_cached_scope(scope_id):
        try:
            with open(_SCOPE_CACHE, 'w', encoding='utf-8') as fh:
                json.dump({'scope_id': scope_id}, fh, ensure_ascii=False)
        except Exception as exc:
            logger.warning('could not cache scope id: %s', exc)

    def ensure_scope(self):
        """Reuse the cached Scope, or create one on first run."""
        if self.scope_ready:
            return True

        for candidate in (self.scope_id, self._read_cached_scope()):
            if not candidate:
                continue
            try:
                resp = self.session.get(self._url(f'/v1/scopes/{candidate}'), timeout=5)
                if resp.status_code == 200:
                    self.scope_id = candidate
                    self.scope_ready = True
                    self._write_cached_scope(candidate)
                    return True
            except Exception:
                pass

        created = self._post('/v1/scopes', {
            'title': 'StudyMind Learning',
            'summary': '学习进度、薄弱知识点与检索行为的记忆作用域',
            'idempotency_key': 'studymind-default-scope',
        })
        if created and created.get('scope_id'):
            self.scope_id = created['scope_id']
            self.scope_ready = True
            self._write_cached_scope(self.scope_id)
            logger.info('PowerContext scope created: %s', self.scope_id)
            return True
        return False

    # ---------- health ----------

    def health_check(self):
        try:
            resp = self.session.get(self._url('/health/ready'), timeout=3)
            if resp.status_code != 200:
                return False
            return self.ensure_scope()
        except Exception as exc:
            logger.warning('PowerContext health check failed: %s', exc)
            return False

    # ---------- memory ----------

    def save_memory(self, content, memory_type='note', metadata=None):
        """Write one memory entry into the current Scope."""
        if not self.ensure_scope():
            return None
        payload = {
            'scope_id': self.scope_id,
            'kind': memory_type or 'note',
            'text': content,
        }
        if metadata:
            payload['reason'] = json.dumps(metadata, ensure_ascii=False)[:500]
        data = self._post('/v1/memory/remember', payload)
        if data and data.get('records'):
            record = data['records'][0]
            logger.info('PowerContext remember: kind=%s artifact=%s',
                        memory_type, record.get('artifact', {}).get('artifact_id'))
            return {
                'status': 'saved',
                'artifact_id': record.get('artifact', {}).get('artifact_id'),
                'revision': record.get('artifact', {}).get('revision'),
                'scope_id': self.scope_id,
            }
        return None

    def recall_memories(self, query, limit=10):
        """Recall memories relevant to a query."""
        if not self.ensure_scope():
            return []
        data = self._post('/v1/memory/search', {
            'scope_id': self.scope_id,
            'query': query,
            'limit': max(1, min(limit, 50)),
        })
        if not data:
            return []
        results = []
        for hit in data.get('hits', []):
            mem = hit.get('memory', {})
            artifact = mem.get('artifact', {})
            results.append({
                'id': artifact.get('artifact_id'),
                'content': mem.get('text', ''),
                'family': mem.get('kind', 'memory'),
                'metadata': {'revision': artifact.get('revision')},
                'score': round(hit.get('score', 0.0), 4),
                'matched_by': hit.get('matched_by', []),
            })
        return results

    def get_prepared_context(self, query, max_bytes=4000):
        """Prepared context block with citations, used by the answer flow."""
        if not self.ensure_scope():
            return None
        return self._post('/v1/context/prepare', {
            'scope_id': self.scope_id,
            'query': query,
            'max_bytes': max(512, min(max_bytes, 32768)),
        })

    # ---------- domain helpers ----------

    def save_learning_progress(self, subject, topic, progress_pct, notes=''):
        return self.save_memory(
            content=f'学习进度 | {subject} > {topic} | 完成度 {progress_pct}% | {notes}'.strip(),
            memory_type='progress',
            metadata={'subject': subject, 'topic': topic, 'progress': progress_pct},
        )

    def save_weak_point(self, subject, topic, description):
        return self.save_memory(
            content=f'薄弱知识点 | {subject} > {topic} | {description}',
            memory_type='weak-point',
            metadata={'subject': subject, 'topic': topic},
        )

    def save_experience(self, situation, action, outcome, lesson):
        return self.save_memory(
            content=(f'学习经验 | 情境: {situation} | 行动: {action} | '
                     f'结果: {outcome} | 经验: {lesson}'),
            memory_type='experience',
            metadata={'situation': situation[:50]},
        )

    def create_handoff(self, desc, steps):
        return self.save_memory(
            content=f'学习会话交接 | {desc} | 下一步: {"; ".join(steps or [])}',
            memory_type='handoff',
            metadata={'steps': steps},
        )

    def get_learning_summary(self, subject=None):
        query = f'学习进度 薄弱知识点 {subject or ""}'.strip()
        memories = self.recall_memories(query, limit=50)
        if subject:
            memories = [m for m in memories if subject in m.get('content', '')]
        return {
            'total_memories': len(memories),
            'scope_id': self.scope_id,
            'memories': memories,
        }


class FallbackMemoryStore:
    """In-memory memory store used only when PowerContext is unreachable."""

    def __init__(self):
        self.memories = []
        self._counter = 0
        self.scope_id = 'memory-fallback'
        self.scope_ready = False

    def health_check(self):
        return False

    def _add(self, content, family, metadata=None):
        self._counter += 1
        entry = {
            'id': f'mem_{self._counter}',
            'content': content,
            'family': family,
            'metadata': metadata or {},
            'ts': datetime.now().isoformat(timespec='seconds'),
        }
        self.memories.append(entry)
        return {'status': 'saved_in_memory', 'artifact_id': entry['id']}

    def save_memory(self, content, memory_type='note', metadata=None):
        return self._add(content, memory_type, metadata)

    def recall_memories(self, query, limit=10):
        tokens = [t for t in query.lower().split() if t]
        scored = []
        for mem in self.memories:
            text = mem['content'].lower()
            score = sum(1 for t in tokens if t in text)
            if score:
                scored.append((score, mem))
        scored.sort(key=lambda x: x[0], reverse=True)
        return [{**m, 'score': s} for s, m in scored[:limit]]

    def get_prepared_context(self, query, max_bytes=4000):
        return {'items': self.recall_memories(query, limit=10), 'max_bytes': max_bytes}

    def save_learning_progress(self, subject, topic, progress_pct, notes=''):
        return self._add(f'学习进度 | {subject} > {topic} | 完成度 {progress_pct}% | {notes}',
                         'progress', {'subject': subject, 'topic': topic})

    def save_weak_point(self, subject, topic, description):
        return self._add(f'薄弱知识点 | {subject} > {topic} | {description}',
                         'weak-point', {'subject': subject, 'topic': topic})

    def save_experience(self, situation, action, outcome, lesson):
        return self._add(f'学习经验 | {situation} | {action} | {outcome} | {lesson}',
                         'experience')

    def create_handoff(self, desc, steps):
        return self._add(f'学习会话交接 | {desc} | 下一步: {"; ".join(steps or [])}',
                         'handoff')

    def get_learning_summary(self, subject=None):
        items = self.memories
        if subject:
            items = [m for m in items if subject in m['content']]
        return {'total_memories': len(items), 'memories': items}
